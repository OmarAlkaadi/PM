-- ---------------------------------------------------------------------
--  Views
-- ---------------------------------------------------------------------

-- Personendaten mit Haus und Haustyp (US 1 / US 2)
CREATE VIEW v_kunde_haus AS
SELECT k.idKunde,
       k.Kundennummer,
       k.Vorname,
       k.Nachname,
       k.Telefon,
       k.email,
       h.Hausnr,
       ht.idHaustyp,
       ht.Beschreibung AS Haustyp
FROM Kunde k
LEFT JOIN Haus    h  ON h.Hausnr     = k.Haus_Hausnr
LEFT JOIN Haustyp ht ON ht.idHaustyp = h.Haustyp_idHaustyp;

-- Alle gewählten Sonderwünsche je Kunde (US 3, 6, 7)
CREATE VIEW v_kunde_sonderwuensche AS
SELECT k.idKunde,
       k.Vorname,
       k.Nachname,
       h.Hausnr,
       swk.idSonderwunschkategorie,
       swk.Kategorie,
       sw.idSonderwunsch,
       sw.Beschreibung AS Sonderwunsch,
       sw.Preis
FROM Kunde k
JOIN Haus                  h   ON h.Hausnr = k.Haus_Hausnr
JOIN Sonderwunsch_has_Haus swh ON swh.Haus_Hausnr = h.Hausnr
JOIN Sonderwunsch          sw  ON sw.idSonderwunsch = swh.Sonderwunsch_idSonderwunsch
JOIN Sonderwunschkategorie swk ON swk.idSonderwunschkategorie = sw.Sonderwunschkategorie_idSonderwunschkategorie;

-- Preis je Kategorie und Kunde (z. B. Gesamtpreis nur für "Heizungen")
CREATE VIEW v_kunde_preis_pro_kategorie AS
SELECT idKunde,
       Hausnr,
       idSonderwunschkategorie,
       Kategorie,
       COUNT(*)                 AS Anzahl,
       COALESCE(SUM(Preis), 0)  AS Summe
FROM v_kunde_sonderwuensche
GROUP BY idKunde, Hausnr, idSonderwunschkategorie, Kategorie;

-- Gesamtpreis aller Sonderwünsche je Kunde (auch Kunden ohne Wünsche -> 0)
CREATE VIEW v_kunde_gesamtpreis AS
SELECT k.idKunde,
       k.Vorname,
       k.Nachname,
       k.Haus_Hausnr AS Hausnr,
       COALESCE(SUM(sw.Preis), 0) AS Gesamtpreis
FROM Kunde k
LEFT JOIN Sonderwunsch_has_Haus swh ON swh.Haus_Hausnr = k.Haus_Hausnr
LEFT JOIN Sonderwunsch          sw  ON sw.idSonderwunsch = swh.Sonderwunsch_idSonderwunsch
GROUP BY k.idKunde, k.Vorname, k.Nachname, k.Haus_Hausnr;

COMMIT;
