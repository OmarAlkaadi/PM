CREATE TABLE Haustyp (
    idHaustyp     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Bild          BYTEA,                      -- MySQL BLOB -> BYTEA
    Beschreibung  VARCHAR(45)
);

CREATE TABLE Haus (
    Hausnr             INT PRIMARY KEY,
    Haustyp_idHaustyp  INT NOT NULL
        REFERENCES Haustyp (idHaustyp)
);

CREATE TABLE Kunde (
    idKunde      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Ergaenzung zum ER-Modell: fachliche Kundennummer aus der GUI
    -- (nur Ziffern, fuehrende Nullen erlaubt -> VARCHAR, siehe KundeValidator 1.4)
    Kundennummer VARCHAR(20) NOT NULL
        CONSTRAINT uq_kunde_kundennummer UNIQUE
        CONSTRAINT ck_kunde_kundennummer CHECK (Kundennummer ~ '^[0-9]+$'),
    Haus_Hausnr  INT                          -- ER-Modell: Kunde 1 -- 0..1 Haus
        CONSTRAINT uq_kunde_haus UNIQUE
        REFERENCES Haus (Hausnr),
    Vorname      VARCHAR(45) NOT NULL,
    Nachname     VARCHAR(45) NOT NULL,
    Telefon      VARCHAR(45),
    email        VARCHAR(45)
);

CREATE TABLE Sonderwunschkategorie (
    idSonderwunschkategorie  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Kategorie                VARCHAR(45)
);

CREATE TABLE Sonderwunsch (
    idSonderwunsch  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Beschreibung    VARCHAR(45) NOT NULL,
    Preis           INT CHECK (Preis IS NULL OR Preis >= 0),   -- in Euro
    Sonderwunschkategorie_idSonderwunschkategorie INT NOT NULL
        REFERENCES Sonderwunschkategorie (idSonderwunschkategorie)
);

CREATE TABLE Sonderwunsch_has_Haus (
    Sonderwunsch_idSonderwunsch INT NOT NULL
        REFERENCES Sonderwunsch (idSonderwunsch) ON DELETE CASCADE,
    Haus_Hausnr                 INT NOT NULL
        REFERENCES Haus (Hausnr) ON DELETE CASCADE,
    PRIMARY KEY (Sonderwunsch_idSonderwunsch, Haus_Hausnr)
);

-- Indizes auf Fremdschlüssel (MySQL legt die automatisch an, PostgreSQL nicht)
CREATE INDEX idx_haus_haustyp           ON Haus (Haustyp_idHaustyp);
CREATE INDEX idx_sonderwunsch_kategorie ON Sonderwunsch (Sonderwunschkategorie_idSonderwunschkategorie);
CREATE INDEX idx_swhh_haus              ON Sonderwunsch_has_Haus (Haus_Hausnr);

